
import os
import numpy as np
import torch

# ==================================================
# 1. Configuration
# ==================================================

INPUT_PATH = "outputs/first_test.pt"
OUTPUT_PATH = "outputs/pointcloud_10.ply"

# Remove the lowest 50% confidence points
CONFIDENCE_PERCENTILE = 10
# Limit point cloud size for easier visualization
MAX_POINTS = 400000




# ==================================================
# 2. Load saved VGGT predictions
# ==================================================

print("Loading VGGT predictions...", flush=True)

if not os.path.exists(INPUT_PATH):
    raise FileNotFoundError(
        f"Cannot find {INPUT_PATH}"
    )

# Load only a file generated by your own trusted script
predictions = torch.load(
    INPUT_PATH,
    map_location="cpu"
)

print("Available keys:", list(predictions.keys()))

required_keys = [
    "world_points",
    "world_points_conf",
    "images"
]

for key in required_keys:
    if key not in predictions:
        raise KeyError(f"Missing prediction: {key}")


# ==================================================
# 3. Convert tensors to NumPy
# ==================================================

points = predictions["world_points"].numpy()
confidence = predictions["world_points_conf"].numpy()
images = predictions["images"].numpy()

print("Original points shape:", points.shape)
print("Confidence shape:", confidence.shape)
print("Images shape:", images.shape)


# ==================================================
# 4. Remove batch dimension if present
# ==================================================

# Expected points: [B, S, H, W, 3]
if points.ndim == 5:
    if points.shape[0] != 1:
        raise ValueError("Expected batch size 1")
    points = points[0]

# Expected confidence: [B, S, H, W]
if confidence.ndim == 4:
    if confidence.shape[0] != 1:
        raise ValueError("Expected batch size 1")
    confidence = confidence[0]

# Expected images: [B, S, 3, H, W]
if images.ndim == 5:
    if images.shape[0] != 1:
        raise ValueError("Expected batch size 1")
    images = images[0]


# ==================================================
# 5. Convert images to RGB layout
# ==================================================

# Convert [S, 3, H, W] to [S, H, W, 3]
if images.ndim == 4 and images.shape[1] == 3:
    images = np.transpose(images, (0, 2, 3, 1))

if images.shape[-1] != 3:
    raise ValueError(
        f"Unexpected image shape: {images.shape}"
    )

# Images are expected to be in [0, 1]
colors = np.clip(images, 0, 1)
colors = (colors * 255).astype(np.uint8)


# ==================================================
# 6. Flatten point cloud data
# ==================================================

points = points.reshape(-1, 3)
confidence = confidence.reshape(-1)
colors = colors.reshape(-1, 3)

if not (
    len(points) == len(confidence) == len(colors)
):
    raise ValueError(
        "Point, confidence, and color counts do not match"
    )

print("Total predicted points:", len(points))


# ==================================================
# 7. Remove invalid points
# ==================================================

valid_mask = (
    np.isfinite(points).all(axis=1)
    & np.isfinite(confidence)
    & (confidence > 1e-5)
)

points = points[valid_mask]
confidence = confidence[valid_mask]
colors = colors[valid_mask]

if len(points) == 0:
    raise RuntimeError("No valid 3D points found")

print("Valid points:", len(points))


# ==================================================
# 8. Confidence filtering
# ==================================================

threshold = np.percentile(
    confidence,
    CONFIDENCE_PERCENTILE
)

mask = confidence >= threshold

points = points[mask]
colors = colors[mask]

print("After confidence filtering:", len(points))


# ==================================================
# 9. Limit number of points
# ==================================================

if len(points) > MAX_POINTS:

    rng = np.random.default_rng(42)

    selected = rng.choice(
        len(points),
        size=MAX_POINTS,
        replace=False
    )

    points = points[selected]
    colors = colors[selected]

print("Final point count:", len(points))


# ==================================================
# 10. Save colored point cloud as PLY
# ==================================================

def save_ply(filename, xyz, rgb):

    vertex_data = np.empty(
        len(xyz),
        dtype=[
            ("x", "<f4"),
            ("y", "<f4"),
            ("z", "<f4"),
            ("red", "u1"),
            ("green", "u1"),
            ("blue", "u1")
        ]
    )

    vertex_data["x"] = xyz[:, 0]
    vertex_data["y"] = xyz[:, 1]
    vertex_data["z"] = xyz[:, 2]

    vertex_data["red"] = rgb[:, 0]
    vertex_data["green"] = rgb[:, 1]
    vertex_data["blue"] = rgb[:, 2]

    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        f"element vertex {len(xyz)}\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "property uchar red\n"
        "property uchar green\n"
        "property uchar blue\n"
        "end_header\n"
    )

    with open(filename, "wb") as f:
        f.write(header.encode("ascii"))
        vertex_data.tofile(f)


os.makedirs("outputs", exist_ok=True)

print("Exporting PLY...", flush=True)

save_ply(
    OUTPUT_PATH,
    points,
    colors
)

print("===================================")
print("POINT CLOUD EXPORT SUCCESSFUL!")
print("Output:", OUTPUT_PATH)
print("Number of points:", len(points))
print("File size:",
      round(os.path.getsize(OUTPUT_PATH) / 1024**2, 2),
      "MB")
print("===================================")
